-- 48. Calculate the percentage contribution of each product category to the overall sales revenue.
SELECT 
    p.category,
    SUM(o.total_amount) AS category_revenue,
    ROUND((SUM(o.total_amount) * 100.0 / (SELECT SUM(total_amount) FROM Orders)), 2) AS percentage_contribution
FROM Products p
JOIN Orders o ON p.product_id = o.product_id
GROUP BY p.category;

-- 49. Rank all customers based on their total purchase amount using PostgreSQL window functions such as RANK() or DENSE_RANK().
SELECT 
    c.customer_id,
    c.customer_name,
    SUM(o.total_amount) AS total_purchase_amount,
    DENSE_RANK() OVER (ORDER BY SUM(o.total_amount) DESC) AS customer_rank
FROM Customers c
JOIN Orders o ON c.customer_id = o.customer_id
GROUP BY c.customer_id, c.customer_name;

-- 50. Write a comprehensive SQL query using appropriate INNER JOIN, LEFT JOIN, GROUP BY, and ORDER BY clauses to generate a report containing Customer Name, Product Name, Order Date, Quantity, Discount Percentage, Total Amount, Payment Method, Order Status, Salesperson, Customer City, and Product Category. Display the report in descending order based on the Order Date.
SELECT 
    c.customer_name,
    p.product_name,
    o.order_date,
    o.quantity,
    o.discount_percent,
    o.total_amount,
    o.payment_method,
    o.order_status,
    o.salesperson,
    c.city AS customer_city,
    p.category AS product_category
FROM Orders o
INNER JOIN Customers c ON o.customer_id = c.customer_id
LEFT JOIN Products p ON o.product_id = p.product_id
ORDER BY o.order_date DESC;