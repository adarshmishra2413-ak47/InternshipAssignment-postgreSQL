-- 31. Calculate the total purchase amount made by each customer and display the results in descending order of total purchase value.
SELECT c.customer_id, c.customer_name, SUM(o.total_amount) AS total_purchase_amount
FROM Customers c
JOIN Orders o ON c.customer_id = o.customer_id
GROUP BY c.customer_id, c.customer_name
ORDER BY total_purchase_amount DESC;

